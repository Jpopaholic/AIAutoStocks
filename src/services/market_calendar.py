def is_market_closed(dt_or_str: Union[datetime, date, str]) -> Tuple[bool, str]:
    """
    判斷指定日期是否為台股休市日（週末或國定假日/特定節日）。
    :param dt_or_str: datetime, date 或 'YYYY-MM-DD' 字串
    :return: (is_closed: bool, reason: str)
    """
    if isinstance(dt_or_str, str):
        try:
            target_date = datetime.strptime(dt_or_str.split("T")[0].split(" ")[0], "%Y-%m-%d").date()
        except ValueError:
            return False, ""
    elif isinstance(dt_or_str, datetime):
        target_date = dt_or_str.date()
    elif isinstance(dt_or_str, date):
        target_date = dt_or_str
    else:
        return False, ""

    date_str = target_date.strftime("%Y-%m-%d")

    # 1. 檢查國定假日行事曆
    if date_str in TWSE_HOLIDAYS:
        return True, TWSE_HOLIDAYS[date_str]

    # 2. 檢查週末 (台股即使行政機關補班，週六週日一律不開盤)
    if target_date.weekday() in (5, 6):
        day_name = "週六" if target_date.weekday() == 5 else "週日"
        return True, f"週末非交易日 ({day_name})"

    return False, ""

def is_trading_day(dt_or_str: Union[datetime, date, str]) -> bool:
    """
    判斷指定日期是否為台股正常交易開盤日。
    """
    closed, _ = is_market_closed(dt_or_str)
    return not closed
